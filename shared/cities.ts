const CITY_BY_NAME = new Map(CITIES.map((c) => [c.name.toLowerCase(), c]))

export function findCity(name: string): City | undefined {
  return CITY_BY_NAME.get(name.trim().toLowerCase())
}

let displayNames: Intl.DisplayNames | null | undefined

/** English country name for an ISO code, falling back to the code itself. */
export function countryName(cc: string): string {
  if (cc === 'XK') return 'Kosovo'
  if (displayNames === undefined) {
    try {
      displayNames = new Intl.DisplayNames(['en'], { type: 'region' })
    } catch {
      displayNames = null
    }
  }
  return displayNames?.of(cc) ?? cc
}
